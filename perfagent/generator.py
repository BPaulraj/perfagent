"""Generate runnable k6 scripts (protocol + browser) from the approved catalog and workload model."""

import json
import re
import shutil

from perfagent import catalog as cat
from perfagent.config import K6_LIB, Project
from perfagent.util import now_iso, read_json, render, write_text

MARKER = "// GENERATED by perfagent - delete this line to protect manual edits from regeneration"
API_KEYS = ("method", "path", "query", "headers", "body", "form", "expect", "extract", "assert_text", "follow_redirects", "compute")
WEB_KEYS = ("action", "url", "selector", "value", "key", "wait", "timeout", "navigates", "attr", "pattern", "all", "var", "compute")
COMPUTE_KEYS = ("compute",)
HOOKS_STUB = ("// Project-specific compute helpers for catalog `compute:` steps (copied from projects/<name>/hooks.js).\n"
              "// export function myHelper(a, b) { return ...; }\n"
              "export {};\n")


def step_js(step: dict, tag: str) -> dict:
    keys = {"web": WEB_KEYS, "compute": COMPUTE_KEYS}.get(step.get("kind"), API_KEYS)
    js = {k: step[k] for k in keys if step.get(k) is not None}
    if "method" in js:
        js["method"] = js["method"].upper()
    js["tag"] = tag
    return js


def cmd_generate(project: Project, force: bool = False) -> None:
    workload_file = project.design_dir / "workload.json"
    if not workload_file.exists():
        raise SystemExit("No workload model. Run: python -m perfagent design " + project.name)
    workload = read_json(workload_file)
    scenarios = {s["id"]: s for s in cat.load(project)["scenarios"]}
    out = project.scripts_dir

    (out / "lib").mkdir(parents=True, exist_ok=True)
    shutil.copy(K6_LIB / "common.js", out / "lib" / "common.js")
    shutil.copy(workload_file, out / "workload.json")
    if project.data_dir.exists():
        shutil.copytree(project.data_dir, out / "data", dirs_exist_ok=True)
    hooks = project.dir / "hooks.js"
    write_text(out / "hooks.js", hooks.read_text(encoding="utf-8") if hooks.exists() else HOOKS_STUB)

    for w in workload["scenarios"]:
        s = scenarios[w["id"]]
        target = out / "scenarios" / f"{w['fn']}.js"
        if target.exists() and not force and MARKER not in target.read_text(encoding="utf-8"):
            print(f"  kept   {target.name} (manually edited - use --force to overwrite)")
            continue
        steps = [{**st, "kind": st.get("kind", "api"), "name": st.get("name") or st.get("path") or st.get("action") or "compute",
                  "think_time": st.get("think_time", 1), "js": step_js(st, tag)}
                 for st, tag in zip(s.get("steps") or [], w["step_tags"])]
        template = "scenario_web.js.j2" if w["kind"] == "web" else "scenario_api.js.j2"
        write_text(target, render(template, marker=MARKER, s=s, w=w, steps=steps))
        print(f"  wrote  scenarios/{target.name}")

    write_text(out / "main.js", render("main.js.j2", workload=workload, generated=now_iso()))
    # secrets the scripts expect at runtime ({{env.NAME}} placeholders + auth config)
    auth = workload.get("auth") or {}
    blob = json.dumps([scenarios[w["id"]].get("steps") for w in workload["scenarios"]])
    if auth.get("type") == "login":
        blob += json.dumps(auth.get("login") or {})
    env_vars = sorted(set(re.findall(r"\{\{\s*env\.(\w+)\s*\}\}", blob)) | auth_env(workload.get("auth") or {}))
    write_text(out / "README.md", render("scripts_readme.md.j2", workload=workload, generated=now_iso(), env_vars=env_vars,
                                         base_url=project.target.get("api_base_url") or "<api base url>",
                                         web_url=project.target.get("web_url") or "<web url>"))
    print(f"  wrote  main.js, README.md\nScripts ready in {out}  (standalone: k6 run main.js - see README.md)")


def auth_env(auth: dict) -> set:
    return {"bearer": {auth.get("token_env")}, "apikey": {auth.get("apikey_env")},
            "basic": {auth.get("username_env"), auth.get("password_env")}}.get(auth.get("type"), set()) - {None}
